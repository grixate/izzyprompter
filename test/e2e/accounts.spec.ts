import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'

function fixtureToken(pro = false) {
  const output = execFileSync('mix', ['run', '--no-start', '-e', `
    Application.ensure_all_started(:ecto_sql)
    Application.ensure_all_started(:postgrex)
    {:ok, _} = Teleprompter.Repo.start_link()
    user = Teleprompter.Repo.insert!(%Teleprompter.Accounts.User{email: Ecto.UUID.generate() <> "@example.com"})
    if ${pro} do
      intent = Teleprompter.Repo.insert!(%Teleprompter.Commerce.Intent{user_id: user.id})
      attempt = Teleprompter.Repo.insert!(%Teleprompter.Commerce.Attempt{intent_id: intent.id,
        provider: "lava", environment: "production", currency: "USD", amount_minor: 2900,
        external_id: Ecto.UUID.generate(), status: "paid"})
      Teleprompter.Repo.insert!(%Teleprompter.Commerce.Grant{user_id: user.id, attempt_id: attempt.id})
    end
    IO.write("LOGIN_TOKEN=" <> Teleprompter.Accounts.issue_token(user.id, "login", 900))
  `], { cwd: 'api', env: { ...process.env, MIX_ENV: 'test', DATABASE_URL: process.env.IZZY_E2E_DATABASE_URL }, encoding: 'utf8' })
  const token = output.match(/LOGIN_TOKEN=([A-Za-z0-9_-]{43})/)?.[1]
  if (!token) throw new Error('Could not seed isolated account fixture')
  return token
}

test.describe('account workspace with PostgreSQL', () => {
  test.skip(!process.env.IZZY_E2E_DATABASE_URL, 'Set IZZY_E2E_DATABASE_URL to a migrated disposable PostgreSQL database')
  test('sign in, save before pairing, recover offline draft, resolve conflict and sync a remote edit', async ({ page, context }, testInfo) => {
    test.setTimeout(60_000)
    page.on('dialog', dialog => void dialog.accept())
    const errors: string[] = []
    // WebKit reports our deliberate route.abort() as an access-control page
    // error even though fetch rejects normally and the application handles it.
    page.on('pageerror', error => { if (!error.message.includes('due to access control checks.')) errors.push(error.message) })
    const token = fixtureToken()
    await page.goto(`/account/login#token=${token}`)
    await page.getByRole('button', { name: 'Sign in to IZZY', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Your scripts.', exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('account-library.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('account-library-mobile.png'), fullPage: true })
    await page.setViewportSize({ width: 1280, height: 900 })
    await page.getByRole('button', { name: 'New script', exact: true }).click()
    await expect(page).toHaveURL(/\/account\/scripts\/[a-f0-9-]+$/)
    const scriptUrl = page.url()
    const text = page.getByRole('textbox', { name: 'Saved script text', exact: true })
    await text.fill('Opening for the camera.\n\nSecond paragraph for a remote correction.')
    await expect(page.getByRole('status')).toHaveText('Saved to account')
    const saved = await page.evaluate(async () => (await fetch(`/api/account/scripts/${location.pathname.split('/')[3]}`)).json())
    expect(saved.document.blocks[0].text).toBe('Opening for the camera.')
    await page.screenshot({ path: testInfo.outputPath('account-editor.png'), fullPage: true })
    await page.route('**/api/account/**', route => route.abort())
    await text.fill('Local offline opening.\n\nSecond paragraph for a remote correction.')
    await expect(page.getByRole('status')).toContainText('Saved on this device')
    await page.reload()
    await expect(text).toHaveValue('Local offline opening.\n\nSecond paragraph for a remote correction.')
    const second = await context.newPage()
    await second.goto(scriptUrl)
    await second.getByRole('textbox', { name: 'Saved script text', exact: true }).fill('A concurrent opening.\n\nSecond paragraph for a remote correction.')
    await expect(second.getByRole('status')).toHaveText('Saved to account')
    await page.unroute('**/api/account/**')
    await page.evaluate(() => window.dispatchEvent(new Event('online')))
    await expect(page.getByRole('button', { name: 'Keep my version', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Keep my version', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('Saved to account')
    await expect(second.getByRole('textbox', { name: 'Saved script text', exact: true })).toHaveValue('Local offline opening.\n\nSecond paragraph for a remote correction.')
    await page.getByRole('button', { name: 'SET UP PROMPTER', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const displayUrl = await dialog.getByRole('link', { name: 'Open reading screen' }).getAttribute('href')
    const remoteUrl = await dialog.getByRole('textbox', { name: 'Remote link' }).inputValue()
    const display = await context.newPage()
    await display.goto(displayUrl!)
    const remote = await context.newPage()
    await remote.goto(remoteUrl)
    await expect(remote.getByRole('button', { name: 'Quick edit current paragraph' })).toBeEnabled()
    await remote.getByRole('button', { name: 'Quick edit current paragraph' }).click()
    await remote.getByRole('textbox', { name: 'CURRENT PARAGRAPH' }).fill('A correction from the phone.')
    await expect(display.locator('.script-track')).toContainText('A correction from the phone.')
    await expect(text).toHaveValue(/A correction from the phone\./)
    await expect(second.getByRole('textbox', { name: 'Saved script text', exact: true })).toHaveValue(/A correction from the phone\./)
    await remote.getByRole('button', { name: 'DONE', exact: false }).click()
    await dialog.getByRole('button', { name: 'Back to script', exact: true }).click()
    await page.getByRole('button', { name: 'End session', exact: true }).click()
    expect(errors).toEqual([])
    await second.close(); await display.close(); await remote.close()
  })

  test('a default Pro preset and explicit live changes reach both displays', async ({ page, context }) => {
    test.setTimeout(60_000)
    await page.goto(`/account/login#token=${fixtureToken(true)}`)
    await page.getByRole('button', { name: 'Sign in to IZZY', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Your scripts.', exact: true })).toBeVisible()
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Studio')
    await page.getByRole('slider', { name: /Text size/ }).fill('90')
    await page.getByRole('checkbox', { name: 'Mirror text', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Use by default', exact: true }).check()
    await page.getByRole('button', { name: 'Save preset', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Preset saved')
    await page.getByRole('button', { name: 'New script', exact: true }).click()
    await page.getByRole('textbox', { name: 'Saved script text', exact: true }).fill('Reading words in the studio. '.repeat(80) + '\n\nThe next paragraph.')
    await expect(page.getByRole('status')).toHaveText('Saved to account')
    await page.getByRole('button', { name: 'SET UP PROMPTER', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const href = await dialog.getByRole('link', { name: 'Open reading screen' }).getAttribute('href')
    const first = await context.newPage(), second = await context.newPage()
    await first.goto(href!); await second.goto(href!)
    for (const display of [first, second]) {
      await expect(display.locator('.network-state')).toHaveText('CONNECTED')
      await expect(display.locator('.standalone-display')).toHaveCSS('--prompt-size', '90px')
      await expect(display.locator('.script-content')).toHaveClass(/is-mirrored/)
    }
    await dialog.getByRole('button', { name: 'Back to script', exact: true }).click()
    const library = await context.newPage()
    await library.goto('/account')
    await library.getByRole('combobox', { name: 'PRESET', exact: true }).selectOption({ label: 'Studio · default' })
    await library.getByRole('slider', { name: /Text size/ }).fill('70')
    await library.getByRole('button', { name: 'Save preset', exact: true }).click()
    await expect(library.getByRole('status')).toContainText('Preset saved')
    await expect(first.locator('.standalone-display')).toHaveCSS('--prompt-size', '90px')
    await page.getByRole('button', { name: 'Apply live', exact: true }).click()
    for (const display of [first, second]) await expect(display.locator('.standalone-display')).toHaveCSS('--prompt-size', '70px')
    await page.getByRole('button', { name: 'End session', exact: true }).click()
    await first.close(); await second.close(); await library.close()
  })
})
