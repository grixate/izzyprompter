import { test, expect } from '@playwright/test'
import { accountFixture } from './helpers/account'

test.describe('project folders', () => {
  test.skip(!process.env.IZZY_E2E_DATABASE_URL, 'Requires a migrated disposable PostgreSQL database')
  test('Pro organizes scripts, renames projects and removes folders without deleting their scripts', async ({ page }, testInfo) => {
    test.setTimeout(60_000)
    await page.goto(`/account/login#token=${accountFixture(undefined, true).token}`)
    await page.getByRole('button', { name: 'Sign in to IZZY', exact: true }).click()
    const project = page.getByRole('combobox', { name: 'Project', exact: true })
    const createProject = async (name: string) => {
      await page.getByRole('button', { name: 'New project', exact: true }).click()
      await page.getByRole('textbox', { name: 'New project name', exact: true }).fill(name)
      await page.getByRole('button', { name: 'Create project', exact: true }).click()
      await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
      return project.inputValue()
    }
    const interviews = await createProject('Interviews')
    await page.getByRole('button', { name: 'New script', exact: true }).click()
    await page.getByRole('textbox', { name: 'Script title', exact: true }).fill('Episode 1')
    await page.getByRole('textbox', { name: 'Saved script text', exact: true }).fill('Synthetic interview opening.')
    await expect(page.getByRole('status')).toHaveText('Saved to account')
    await page.getByRole('link', { name: 'All scripts', exact: true }).click()
    await project.selectOption(interviews)
    await expect(page.locator('.script-card')).toHaveCount(1)
    await page.getByRole('button', { name: 'Rename project', exact: true }).click()
    await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('Client interviews')
    await page.getByRole('button', { name: 'Save project name', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Client interviews', exact: true })).toBeVisible()
    const presentations = await createProject('Presentations')
    await expect(page.locator('.script-card')).toHaveCount(0)
    await project.selectOption('')
    await page.getByRole('combobox', { name: 'Project for Episode 1', exact: true }).selectOption(presentations)
    await project.selectOption(interviews)
    await expect(page.locator('.script-card')).toHaveCount(0)
    await project.selectOption(presentations)
    await expect(page.locator('.script-card')).toHaveCount(1)
    await page.getByRole('button', { name: 'Duplicate Episode 1', exact: true }).click()
    await expect(page.locator('.script-card')).toHaveCount(2)
    await expect(project.locator('option:checked')).toHaveText('Presentations (2)')
    await page.screenshot({ path: testInfo.outputPath('projects-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 320, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
    await page.screenshot({ path: testInfo.outputPath('projects-phone.png'), fullPage: true })
    await page.getByRole('button', { name: 'Remove project', exact: true }).click()
    await expect(page.getByText('Remove this folder?', { exact: false })).toBeVisible()
    await page.getByRole('button', { name: 'Confirm remove project', exact: true }).click()
    await expect(project).toHaveValue('')
    await expect(page.locator('.script-card')).toHaveCount(2)
    await project.selectOption('unfiled')
    await expect(page.locator('.script-card')).toHaveCount(2)
    await page.reload()
    await expect(project.locator('option')).not.toContainText(['Presentations'])
    await expect(page.locator('.script-card')).toHaveCount(2)
  })

  test('free accounts cannot create projects through the API', async ({ page }) => {
    await page.goto(`/account/login#token=${accountFixture().token}`)
    await page.getByRole('button', { name: 'Sign in to IZZY', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Your scripts', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'New project', exact: true })).toHaveCount(0)
    const result = await page.evaluate(async () => {
      const account = await (await fetch('/api/account')).json()
      const response = await fetch('/api/account/folders', { method: 'POST', headers: { 'content-type': 'application/json', 'x-csrf-token': account.csrf_token }, body: JSON.stringify({ name: 'Not allowed' }) })
      return { status: response.status, json: await response.json() }
    })
    expect(result).toEqual({ status: 403, json: { reason: 'pro_required' } })
  })
})
