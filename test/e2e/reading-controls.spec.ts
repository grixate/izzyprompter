import { test, expect } from '@playwright/test'

test('phone changes display type, keeps the reading anchor, and edits a different paragraph', async ({ page: editor, browser }, testInfo) => {
  const text = ['Opening words for a synthetic take. '.repeat(20), 'Middle of the synthetic script. '.repeat(30), 'Closing synthetic paragraph.']
  await editor.goto('/')
  await editor.getByRole('textbox', { name: 'Teleprompter script' }).fill(text.join('\n\n'))
  await editor.getByRole('button', { name: 'SET UP PROMPTER' }).click()
  await expect(editor.locator('.network-state')).toHaveText('CONNECTED')
  const displays = await browser.newContext({ viewport: { width: 1280, height: 800 } })
  const phones = await browser.newContext({ viewport: { width: 428, height: 926 }, hasTouch: true })
  try {
    const display = await displays.newPage(), remote = await phones.newPage()
    await display.goto((await editor.getByRole('link', { name: /OPEN DISPLAY/ }).getAttribute('href'))!)
    await remote.goto((await editor.getByRole('link', { name: /OPEN REMOTE/ }).getAttribute('href'))!)
    await expect(remote.getByRole('button', { name: 'Next phrase' })).toBeEnabled()
    await remote.getByRole('button', { name: 'Next phrase' }).click()
    await expect(remote.locator('.phrase-count')).toContainText('02 / 03')
    await remote.getByRole('button', { name: 'Remote settings', exact: true }).click()
    await remote.getByRole('button', { name: 'Increase text size' }).click()
    await expect(display.locator('.standalone-display')).toHaveCSS('--prompt-size', '66px')
    await remote.getByRole('slider', { name: 'TEXT SIZE', exact: true }).fill('90')
    await expect(display.locator('.standalone-display')).toHaveCSS('--prompt-size', '90px')
    await expect(remote.locator('.phrase-count')).toContainText('02 / 03')
    await remote.screenshot({ path: testInfo.outputPath('reading-settings-phone.png') })
    await remote.getByRole('button', { name: 'Close settings' }).click()
    await remote.getByRole('button', { name: 'Quick edit current paragraph' }).click()
    const chooser = remote.getByRole('combobox', { name: 'Text to edit' })
    await expect(chooser).toBeEnabled()
    await chooser.selectOption({ index: 3 })
    await remote.getByRole('textbox', { name: 'CURRENT PARAGRAPH' }).fill('An updated synthetic closing paragraph.')
    await expect(display.locator('.script-track p').nth(2)).toHaveText('An updated synthetic closing paragraph.')
    await expect(remote.getByText('Updated', { exact: true })).toBeVisible()
    await remote.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(remote.locator('.phrase-count')).toContainText('02 / 03')
    await expect(display.locator('.display-footer')).toContainText('STANDBY')
    await remote.getByRole('button', { name: 'Quick edit current paragraph' }).click()
    await remote.getByRole('combobox', { name: 'Text to edit' }).selectOption('document')
    const inserted = 'A new synthetic introduction.'
    const replacement = [inserted, text[0].trim(), text[1].trim(), 'A final rewritten closing.'].join('\n\n')
    await remote.getByRole('textbox', { name: 'SCRIPT TEXT' }).fill(replacement)
    await expect(display.locator('.script-track p')).toHaveCount(4)
    await expect(display.locator('.script-track p').first()).toHaveText(inserted)
    await expect(remote.getByText('Updated', { exact: true })).toBeVisible()
    await remote.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(remote.locator('.phrase-count')).toContainText('03 / 04')
    await remote.reload()
    await remote.getByRole('button', { name: 'Remote settings', exact: true }).click()
    await expect(remote.getByLabel('Current text size')).toContainText('90')
  } finally { await displays.close(); await phones.close() }
})
